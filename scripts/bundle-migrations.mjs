import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

/**
 * Concatenates supabase/migrations/*.sql, in order, into one file you can
 * paste into the Supabase SQL editor in a single go.
 *
 * The migrations remain the source of truth; this output is generated and
 * git-ignored, so the two can never drift.
 */

const dir = "supabase/migrations";
const out = "supabase/bundle.sql";

const files = readdirSync(dir)
  .filter((name) => name.endsWith(".sql"))
  .sort();

const banner = (name) =>
  `\n\n-- ${"=".repeat(72)}\n-- ${name}\n-- ${"=".repeat(72)}\n\n`;

const sql =
  "-- Generated by npm run db:bundle. Do not edit; edit the migrations.\n" +
  "-- Safe to re-run.\n" +
  files.map((name) => banner(name) + readFileSync(join(dir, name), "utf8")).join("");

writeFileSync(out, sql);
console.log(`${out} <- ${files.length} migrations, ${sql.split("\n").length} lines`);
